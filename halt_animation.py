def play_halt_animation(frames=None, delay=0.15, repeat=1, start_row=1, offset_spaces=35):
    if frames is None:
        frames = ascii_frames

    width = shutil.get_terminal_size().columns

    for _ in range(repeat):
        for frame in frames:
            # Clear old frame area
            for row in range(start_row, start_row + 24):
                sys.stdout.write(f"\033[{row};0H" + " " * width)

            # Add fixed offset before each line
            shifted_lines = []
            for line in frame.strip('\n').split('\n'):
                shifted_lines.append(" " * offset_spaces + line)

            sys.stdout.write(f"\033[{start_row};0H" + "\n".join(shifted_lines))
            sys.stdout.flush()
            time.sleep(delay)
