def play_ascii_animation(frames=None, delay=0.15, repeat=1, start_row=1):
    if frames is None:
        frames = ascii_frames

    width = shutil.get_terminal_size().columns
    height = shutil.get_terminal_size().lines

    for _ in range(repeat):
        for frame in frames:
            # Clear old frame area
            for row in range(start_row, start_row + 24):
                sys.stdout.write(f"\033[{row};0H" + " " * width)

            # Center horizontally: calculate padding for each line
            centered_lines = []
            for line in frame.strip('\n').split('\n'):
                pad = max((width - len(line)) // 2, 0)
                centered_lines.append(" " * pad + line)

            sys.stdout.write(f"\033[{start_row};0H" + "\n".join(centered_lines))
            sys.stdout.flush()
            time.sleep(delay)




